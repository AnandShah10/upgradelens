import assert from "node:assert/strict";
import { test } from "node:test";
import { parseYarnLock, parseYarnBerryLock } from "../package/YarnPackageManager";

test("parses a simple single-descriptor entry", () => {
  const lock = `
lodash@^4.17.21:
  version "4.17.21"
  resolved "https://registry.yarnpkg.com/lodash/-/lodash-4.17.21.tgz#679591c564c3bffaae8454cf0b3df370c3d6911c"
  integrity sha512-v2kDEe57lecTulaDIuNTPy3Ry4/GHTpBiVh2WgHVMSCn+hVQhqLxSJlAvvxDcRwLoBiKGhRlxJgbNhKZuFVW2Q==
`;
  const versions = parseYarnLock(lock);
  assert.equal(versions["lodash"], "4.17.21");
});

test("parses a multi-descriptor entry, applying the version to every requested name", () => {
  const lock = `
"lodash@^4.17.0, lodash@^4.17.21":
  version "4.17.21"
  resolved "https://registry.yarnpkg.com/lodash/-/lodash-4.17.21.tgz#..."
`;
  const versions = parseYarnLock(lock);
  assert.equal(versions["lodash"], "4.17.21");
});

test("parses scoped package names correctly", () => {
  const lock = `
"@babel/core@^7.0.0, @babel/core@^7.20.0":
  version "7.24.0"
  resolved "https://registry.yarnpkg.com/@babel/core/-/core-7.24.0.tgz#..."
`;
  const versions = parseYarnLock(lock);
  assert.equal(versions["@babel/core"], "7.24.0");
});

test("parses multiple independent blocks", () => {
  const lock = `
axios@^1.6.0:
  version "1.6.8"
  resolved "https://registry.yarnpkg.com/axios/-/axios-1.6.8.tgz#..."

express@^4.19.0:
  version "4.19.2"
  resolved "https://registry.yarnpkg.com/express/-/express-4.19.2.tgz#..."
`;
  const versions = parseYarnLock(lock);
  assert.equal(versions["axios"], "1.6.8");
  assert.equal(versions["express"], "4.19.2");
});

test("ignores comment lines and blank lines", () => {
  const lock = `
# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


react@^18.2.0:
  version "18.2.0"
  resolved "https://registry.yarnpkg.com/react/-/react-18.2.0.tgz#..."
`;
  const versions = parseYarnLock(lock);
  assert.equal(versions["react"], "18.2.0");
});

test("returns an empty map for an empty file", () => {
  assert.deepEqual(parseYarnLock(""), {});
});

// --- Yarn Berry (v2+) format ------------------------------------------------

test("Berry: parses a simple npm-protocol entry", () => {
  const lock = `__metadata:
  version: 6
  cacheKey: 8

"lodash@npm:^4.17.21":
  version: 4.17.21
  resolution: "lodash@npm:4.17.21"
  checksum: abc
  languageName: node
  linkType: hard
`;
  const versions = parseYarnBerryLock(lock);
  assert.equal(versions["lodash"], "4.17.21");
});

test("Berry: parses a multi-descriptor key, applying the version to every requested name", () => {
  const lock = `__metadata:
  version: 6

"lodash@npm:^4.17.0, lodash@npm:^4.17.21":
  version: 4.17.21
  resolution: "lodash@npm:4.17.21"
  languageName: node
  linkType: hard
`;
  const versions = parseYarnBerryLock(lock);
  assert.equal(versions["lodash"], "4.17.21");
});

test("Berry: parses scoped package names", () => {
  const lock = `__metadata:
  version: 6

"@babel/core@npm:^7.20.0":
  version: 7.24.0
  resolution: "@babel/core@npm:7.24.0"
  languageName: node
  linkType: hard
`;
  const versions = parseYarnBerryLock(lock);
  assert.equal(versions["@babel/core"], "7.24.0");
});

test("Berry: skips the __metadata key itself", () => {
  const lock = `__metadata:
  version: 6
  cacheKey: 8
`;
  const versions = parseYarnBerryLock(lock);
  assert.deepEqual(versions, {});
});

test("Berry: skips workspace:/patch: protocol descriptors (not real published versions)", () => {
  const lock = `__metadata:
  version: 6

"my-workspace-pkg@workspace:packages/api":
  version: 0.0.0-use.local
  resolution: "my-workspace-pkg@workspace:packages/api"
  languageName: unknown
  linkType: soft

"axios@npm:^1.6.0":
  version: 1.6.8
  resolution: "axios@npm:1.6.8"
  languageName: node
  linkType: hard
`;
  const versions = parseYarnBerryLock(lock);
  assert.equal(versions["axios"], "1.6.8");
  assert.equal(versions["my-workspace-pkg"], undefined);
});

test("Berry: returns an empty map for malformed YAML rather than throwing", () => {
  assert.deepEqual(parseYarnBerryLock("not: valid: yaml: : ::"), {});
});

test("Berry: returns an empty map for an empty document", () => {
  assert.deepEqual(parseYarnBerryLock(""), {});
});
